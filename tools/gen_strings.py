"""
Generate Android strings.xml (values, values-ur, values-ar) from the web dictionaries in
chobbar-web/src/i18n/dictionaries so the app and the website share one copy deck.

    python3 tools/gen_strings.py ../chobbar-web/src/i18n/dictionaries

Keys become snake_case ("cart.title" -> cart_title). Placeholders like {count} become positional
%N$s arguments numbered by their order in the English text, so translations may reorder them.
App-only strings live in tools/app_strings.json (same three languages).
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "app/src/main/res"
LANGS = {"en": "values", "ur": "values-ur", "ar": "values-ar"}
PH = re.compile(r"\{(\w+)\}")


def flatten(d, prefix=""):
    out = {}
    for k, v in d.items():
        key = f"{prefix}{k}"
        if isinstance(v, dict):
            out.update(flatten(v, key + "."))
        else:
            out[key] = v
    return out


def escape(text: str) -> str:
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')
    if text.startswith(("@", "?")):
        text = "\\" + text
    return text


def main(dict_dir: str):
    dicts = {lang: flatten(json.loads((Path(dict_dir) / f"{lang}.json").read_text())) for lang in LANGS}
    app = json.loads((ROOT / "tools/app_strings.json").read_text())
    for key, vals in app.items():
        for lang in LANGS:
            dicts[lang][key] = vals[lang]
    en = dicts["en"]
    order = {key: list(dict.fromkeys(PH.findall(text))) for key, text in en.items()}
    for lang, folder in LANGS.items():
        lines = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by tools/gen_strings.py. Do not edit by hand. -->", "<resources>"]
        for key in sorted(en):
            text = dicts[lang].get(key, en[key])
            names = order[key]
            name = re.sub(r"[^a-z0-9_]", "_", key.replace(".", "_").lower())
            value = escape(text)
            if names:
                # Literal percent signs must be doubled in format strings; then insert %N$s args.
                value = value.replace("%", "%%")
                for i, ph in enumerate(names, start=1):
                    value = value.replace("{" + ph + "}", f"%{i}$s")
                lines.append(f'    <string name="{name}">{value}</string>')
            elif "%" in value:
                lines.append(f'    <string name="{name}" formatted="false">{value}</string>')
            else:
                lines.append(f'    <string name="{name}">{value}</string>')
        lines.append("</resources>")
        out = RES / folder
        out.mkdir(parents=True, exist_ok=True)
        (out / "strings.xml").write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"{folder}/strings.xml: {len(en)} strings")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else str(ROOT.parent / "chobbar-web/src/i18n/dictionaries"))
